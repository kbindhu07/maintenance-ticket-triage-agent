"""FastAPI service for the maintenance-ticket triage agent.

Endpoints
  GET  /                -> web UI (frontend/index.html)
  GET  /api/health      -> liveness + model/LLM status
  POST /api/triage      -> triage one ticket (main endpoint)
  POST /api/run         -> same as /api/triage (kept from the starter template)
  GET  /api/queue       -> triage all sample tickets and return a prioritised work queue
  GET  /api/tickets     -> sample tickets for the UI
  GET  /api/metrics     -> evaluation results (reports/metrics.json)
  GET  /api/categories  -> knowledge base: categories, teams, SLAs
  GET  /docs            -> interactive OpenAPI docs (auto-generated by FastAPI)
"""
import json
import os
from contextlib import asynccontextmanager
from pathlib import Path
from typing import Literal, Optional

import pandas as pd
from fastapi import FastAPI, HTTPException
from fastapi.responses import FileResponse
from pydantic import BaseModel, Field

from .agent import TriageAgent
from .knowledge_base import CATEGORIES, PRIORITY, SLA_HOURS
from .llm import LLM_MODEL

BASE = Path(__file__).resolve().parents[1]
DATA = BASE / "data"
FRONTEND = BASE / "frontend" / "index.html"
METRICS = BASE / "reports" / "metrics.json"

STATE: dict = {}


@asynccontextmanager
async def lifespan(app: FastAPI):
    STATE["agent"] = TriageAgent()  # trains (<2 s) or loads the saved model once at startup
    yield


app = FastAPI(title="AI Agent for Maintenance Ticket Prioritization", version="1.0.0", lifespan=lifespan)


class TicketIn(BaseModel):
    text: str = Field(..., min_length=5, max_length=2000, description="Free-text ticket description")
    asset_type: Optional[Literal["solar", "wind", "hydro", "grid", ""]] = Field(
        "", description="Optional. Inferred from the text if empty.")
    ticket_id: Optional[str] = None
    use_llm: bool = Field(True, description="Use the LLM summary if ANTHROPIC_API_KEY is set")


class Query(BaseModel):  # starter-template compatibility
    text: str = ""


def sample_tickets() -> pd.DataFrame:
    frames = [pd.read_csv(DATA / "maintenance_tickets.csv").assign(source="bundled"),
              pd.read_csv(DATA / "holdout_handwritten.csv").assign(source="holdout")]
    return pd.concat(frames, ignore_index=True)


@app.get("/", include_in_schema=False)
def index():
    return FileResponse(FRONTEND)


@app.get("/api/health")
def health():
    return {"status": "ok", "model_loaded": "agent" in STATE,
            "llm_enabled": bool(os.getenv("ANTHROPIC_API_KEY")), "llm_model": LLM_MODEL}


@app.get("/api/demo")
def demo():
    return {"case_study": "AI Agent for Maintenance Ticket Prioritization", "status": "running",
            "try": "POST /api/triage with {\"text\": \"Gearbox vibration increased on WTG-12 with abnormal noise\"}"}


@app.post("/api/triage")
def triage(ticket: TicketIn):
    if not ticket.text.strip():
        raise HTTPException(status_code=422, detail="Ticket text is empty")
    return STATE["agent"].triage(ticket.text.strip(), ticket.asset_type or "", ticket.ticket_id, ticket.use_llm)


@app.post("/api/run")
def run_case(query: Query):
    if len(query.text.strip()) < 5:
        raise HTTPException(status_code=422, detail="Provide at least 5 characters of ticket text")
    return STATE["agent"].triage(query.text.strip(), "", None, use_llm=True)


@app.get("/api/tickets")
def tickets():
    df = sample_tickets()
    return df[["ticket_id", "asset_type", "description", "target_severity", "target_category", "source"]].to_dict("records")


@app.get("/api/queue")
def queue():
    """Triage every sample ticket (no LLM, for speed) and sort into a work queue."""
    if "queue" not in STATE:
        agent = STATE["agent"]
        rows = []
        for r in sample_tickets().itertuples():
            res = agent.triage(r.description, r.asset_type, r.ticket_id, use_llm=False)
            rows.append({"ticket_id": r.ticket_id, "description": r.description, "asset_type": r.asset_type,
                         "category": res["category"]["id"], "category_label": res["category"]["label"],
                         "confidence": res["category"]["confidence"], "severity": res["severity"]["severity"],
                         "level": res["severity"]["level"], "priority": res["routing"]["priority"],
                         "team": res["routing"]["team"], "sla_hours": res["routing"]["sla_hours"],
                         "needs_human_review": res["needs_human_review"],
                         "true_category": r.target_category, "true_severity": r.target_severity})
        # Highest severity first; within a level, tickets needing human review first, then by confidence.
        rows.sort(key=lambda x: (-x["level"], not x["needs_human_review"], -x["confidence"]))
        STATE["queue"] = rows
    return STATE["queue"]


@app.get("/api/metrics")
def metrics():
    if not METRICS.exists():
        raise HTTPException(status_code=404, detail="Run `python scripts/evaluate.py` to generate metrics")
    return json.loads(METRICS.read_text())


@app.get("/api/categories")
def categories():
    return {"categories": {k: {kk: v[kk] for kk in ("label", "team", "base_severity", "asset_types")}
                           for k, v in CATEGORIES.items()},
            "sla_hours": SLA_HOURS, "priority": PRIORITY}
